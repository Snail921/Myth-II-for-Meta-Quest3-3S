"""Generate production Build 434 constants from shared profiles. 471b stays diagnostic-only."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
r=json.loads((ROOT/'src/engine/profiles.json').read_text());p=next(x for x in r['profiles'] if x['id']=='1.8.1-434');assert p['capabilities']['production_bridge']
lines=['/* Generated by tools/generate_engine_profile.py. */','#pragma once','#ifndef MYTH_ENGINE_BUILD','#define MYTH_ENGINE_BUILD 434','#endif','#if MYTH_ENGINE_BUILD != 434','#error This production bridge is only validated for Build 434; use the read-only probe for 471b.','#endif']
for k,v in p['addresses'].items():lines.append('#define MVR_'+k.upper()+' 0x%xu'%v)
(ROOT/'src/engine/profile_434.h').write_text('\n'.join(lines)+'\n')
lines=['package org.mythvr.standalone;','// Generated Build 434 bindings. Build 471b is diagnostic-only.','final class EngineProfile {','    static final String SHA256 = "'+p['sha256']+'";']
for k,v in p['addresses'].items():lines.append('    static final long '+k.upper()+' = 0x%xL;'%v)
lines.append('}')
(ROOT/'src/standalone/EngineProfile.java').write_text('\n'.join(lines)+'\n')
