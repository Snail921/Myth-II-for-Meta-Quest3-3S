"""Generate physical death-animation metadata using original monster death groups.
Match all six collection identity fields, never runtime slots or display names.
"""
import struct
from pathlib import Path
from level_assets import inventory,raw_tag
from build_level_assets import collection_fields
import mons_tag
ROOT=Path(__file__).resolve().parents[1]
def rows(tags):
 result=set()
 for kind,key in tags:
  if kind!='mons':continue
  m=mons_tag.parse_tag(2,bytes(60)+b'mth2'+raw_tag(tags,kind,key));col=m.collection_tag.decode('latin1')
  if ('.256',col) not in tags:continue
  fields=collection_fields(raw_tag(tags,'.256',col));visited=set()
  def group(name):
   key=name.decode('latin1') if isinstance(name,bytes) else name
   if key in visited or ('prgr',key) not in tags:return
   visited.add(key);b=raw_tag(tags,'prgr',key);count=struct.unpack_from('>h',b,4)[0]
   for i in range(count):
    pk=b[32+i*32:36+i*32].decode('latin1')
    if ('proj',pk) not in tags:continue
    p=raw_tag(tags,'proj',pk)
    if p[4:8]!=m.collection_tag:continue # Blood, fire, smoke and other effect libraries are not body art.
    for seq in struct.unpack_from('>3h',p,8):
     if 0<=seq<256:result.add((*fields,seq))
    group(p[16:20])
  group(m.dying_projectile_group_tag);group(m.exploding_projectile_group_tag)
 return sorted(result)
if __name__=='__main__':
 data=rows(inventory());out=ROOT/'src/vr/death_sprite_metadata.h'
 out.write_text('// Generated by tools/prepare_death_sprite_metadata.py from monster death groups.\n#pragma once\nstatic constexpr unsigned deathSpriteMetadata[][7]={\n'+''.join(' {'+','.join(str(x)+'u' for x in r)+'},\n' for r in data)+'};\n',encoding='utf8')
 print('Physical death sequences:',len(data))
